// Bundles src/lib/import/autoImport.ts (and the app modules it uses) into the auto-import Edge
// Function, so the hourly AO bot runs the very same import code as the นำเข้าออเดอร์ screen.
// The app's browser Supabase client (src/lib/supabase.ts) is swapped for the function's
// service-role client (supabase/functions/auto-import/clientShim.ts).
// Run after changing any import code:  node scripts/build-auto-import.mjs
import { build } from 'esbuild'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const appClient = path.join(root, 'src/lib/supabase.ts')

await build({
  entryPoints: [path.join(root, 'src/lib/import/autoImport.ts')],
  outfile: path.join(root, 'supabase/functions/auto-import/bundle.js'),
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  target: 'es2022',
  // Vite's env object does not exist in Deno; nothing on the import path reads it
  define: { 'import.meta.env': '{}' },
  banner: { js: '// GENERATED by scripts/build-auto-import.mjs from src/lib/import/autoImport.ts -- do not edit' },
  plugins: [
    {
      name: 'service-role-client',
      setup(b) {
        b.onResolve({ filter: /\/supabase$/ }, (args) => {
          const p = path.resolve(args.resolveDir, args.path) + '.ts'
          return p === appClient ? { path: path.join(root, 'supabase/functions/auto-import/clientShim.ts') } : undefined
        })
      },
    },
  ],
})
console.log('built supabase/functions/auto-import/bundle.js')
