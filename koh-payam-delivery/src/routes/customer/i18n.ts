export function t(
  lang: Lang,
  key: string,
  vars?: Record<string, string | number>,
): string {
  const raw = STRINGS[lang]?.[key] ?? STRINGS.en[key] ?? key
  if (!vars) return raw
  return raw.replace(/\{(\w+)\}/g, (m, name) =>
    name in vars ? String(vars[name]) : m,
  )
}
